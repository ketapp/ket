#!/usr/bin/env python3
"""Writes the phone's copy of the project glyphs from the desktop's.

The desktop draws a project glyph from an SVG file compiled into the binary
(crates/ket-ui/assets/icons/glyphs, listed in crates/ket-ui/src/ui/glyph.rs).
The phone draws with react-native-svg, which takes shapes rather than files, so
this turns each file into the shapes it is made of and the viewBox they are
drawn on (each glyph keeps its own: most are 16 units, a few 20). One set of
files, read by both: a glyph added or redrawn on the desktop reaches the phone
by running this again, and the phone can never offer a name the desktop does
not have.

Usage:
    python3 scripts/phone-glyphs.py    # writes mobile/app/src/lib/glyphs.ts
"""

from __future__ import annotations

import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ORDER = ROOT / "crates/ket-ui/src/ui/glyph.rs"
FILES = ROOT / "crates/ket-ui/assets/icons/glyphs"
OUT = ROOT / "mobile/app/src/lib/glyphs.ts"

# The attributes each shape is drawn from; everything else on it is the
# fill the whole glyph shares, which the phone sets once.
SHAPES = {
    "path": ["d"],
    "circle": ["cx", "cy", "r"],
    "ellipse": ["cx", "cy", "rx", "ry"],
    "rect": ["x", "y", "width", "height", "rx", "ry"],
    "line": ["x1", "y1", "x2", "y2"],
    "polyline": ["points"],
    "polygon": ["points"],
}


def names() -> list[str]:
    """The glyphs in the desktop's order, read off its table."""
    table = ORDER.read_text()
    body = table[table.index("glyphs![") : table.index("];", table.index("glyphs!["))]
    return re.findall(r'"([a-z0-9-]+)"', body)


def view_box(name: str, svg: ET.Element) -> str:
    """The grid a glyph is drawn on, as its file names it.

    Glyphs are not all on one grid (most are 16 units, a few 20), so each
    carries its own rather than the phone assuming one.
    """
    value = svg.get("viewBox")
    if value is None:
        raise SystemExit(f"{name}.svg has no viewBox")
    numbers = value.replace(",", " ").split()
    if len(numbers) != 4:
        raise SystemExit(f"{name}.svg has a viewBox of {value!r}")
    return " ".join(f"{float(number):g}" for number in numbers)


def shapes(name: str, svg: ET.Element) -> list[dict[str, object]]:
    parts = []
    for element in svg:
        kind = element.tag.rsplit("}", 1)[-1]
        if kind not in SHAPES:
            raise SystemExit(f"{name}.svg has a <{kind}>, which the phone does not draw")
        part: dict[str, object] = {"kind": kind}
        for attribute in SHAPES[kind]:
            value = element.get(attribute)
            if value is None:
                continue
            part[attribute] = value if attribute in ("d", "points") else float(value)
        parts.append(part)
    return parts


def literal(part: dict[str, object]) -> str:
    """A shape as a TypeScript object literal, in the app's quoting."""
    fields = []
    for key, value in part.items():
        if isinstance(value, float):
            fields.append(f"{key}: {value:g}")
        else:
            fields.append(f"{key}: '{value}'")
    return "{ " + ", ".join(fields) + " }"


def main() -> None:
    lines = [
        "// Generated by scripts/phone-glyphs.py from the desktop's glyph files",
        "// (crates/ket-ui/assets/icons/glyphs) — run it again rather than editing.",
        "// Fluent UI System Icons 1.1.346, filled, MIT; see NOTICE.md.",
        "",
        "export type GlyphPart =",
        "  | { kind: 'path'; d: string }",
        "  | { kind: 'circle'; cx: number; cy: number; r: number }",
        "  | { kind: 'ellipse'; cx: number; cy: number; rx: number; ry: number }",
        "  | { kind: 'rect'; x: number; y: number; width: number; height: number; rx?: number; ry?: number }",
        "  | { kind: 'line'; x1: number; y1: number; x2: number; y2: number }",
        "  | { kind: 'polyline'; points: string }",
        "  | { kind: 'polygon'; points: string };",
        "",
        "/** A glyph's filled shapes, on the grid its own `viewBox` names. */",
        "export type Glyph = { viewBox: string; parts: GlyphPart[] };",
        "",
        "/** Every glyph, in the desktop's order. */",
        "export const GLYPHS: Record<string, Glyph> = {",
    ]
    for name in names():
        svg = ET.parse(FILES / f"{name}.svg").getroot()
        lines.append(f"  '{name}': {{")
        lines.append(f"    viewBox: '{view_box(name, svg)}',")
        lines.append("    parts: [")
        lines.extend(f"      {literal(part)}," for part in shapes(name, svg))
        lines.append("    ],")
        lines.append("  },")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
